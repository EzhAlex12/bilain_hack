"""
Модуль динамического профиля пробок Москвы на основе исследования Яндекс.Пробок:
https://yandex.ru/company/researches/2014/ya_traffic_msk_2014

Исследование охватывает дорожную ситуацию в Москве (сентябрь-октябрь):
1. Суточный профиль загруженности дорог Москвы (баллы 1-10 в течение рабочего дня).
2. Асимметрия радиальных магистралей:
   - Утренний час пик (08:00 - 10:00) в центр: задержки до 5x на Шоссе Энтузиастов (Восток)
     и Волгоградском проспекте (Юго-восток).
   - Вечерний час пик (18:00 - 20:00) из центра: на 1-1.5 балла тяжелее утреннего.
3. Кольцевые зоны: между ТТК и МКАД (зона датасетов ВАО, ЮВАО, ЮАО).
4. Иммунитет мультимодального парка: пешие инженеры (тротуары, k=1.10),
   велосипедисты (велодорожки, k=1.15) и общественный транспорт (метро/МЦД/выделенки)
   имеют k_traffic = 1.0 (не зависят от автомобильных заторов).
"""

from typing import Tuple, Dict, Any

# Почасовой профиль среднего балла пробок Москвы по исследованию Яндекса (рабочие дни)
YANDEX_HOURLY_SCORE = {
    6: 1.5,   # 06:00 - ранее утро, свободный город
    7: 3.2,   # 07:00 - начало разъезда
    8: 6.8,   # 08:00 - начало утреннего часа пик
    9: 7.2,   # 09:00 - пик загрузки радиальных магистралей в сторону центра
    10: 5.6,  # 10:00 - постепенный спад
    11: 4.2,  # 11:00 - дневной межпик
    12: 4.0,  # 12:00 - стабильный умеренный трафик
    13: 4.1,  # 13:00 - дневной межпик
    14: 4.3,  # 14:00
    15: 4.8,  # 15:00
    16: 5.5,  # 16:00 - начало предпикового накопления
    17: 6.9,  # 17:00 - вечерний разъезд из офисов
    18: 8.2,  # 18:00 - вечерний час пик (на 1-1.5 балла тяжелее утреннего!)
    19: 7.9,  # 19:00 - глухие заторы из центра в спальные районы
    20: 5.8,  # 20:00 - спад основного потока
    21: 3.6,  # 21:00 - свободные магистрали
    22: 2.1,  # 22:00 - свободный город, возврат в депо
    23: 1.5   # 23:00
}

# Координаты условного центра Москвы (Кремль / Охотный ряд)
MOSCOW_CENTER_COORDS = (55.7558, 37.6173)


def get_yandex_score(t_min: int) -> float:
    """
    Возвращает интерполированный балл Яндекс.Пробок (от 1.0 до 10.0) для заданного времени в минутах от 00:00.
    """
    hour = t_min / 60.0
    h_floor = int(hour)
    h_ceil = min(23, h_floor + 1)
    weight = hour - h_floor

    b_floor = YANDEX_HOURLY_SCORE.get(h_floor, 2.0)
    b_ceil = YANDEX_HOURLY_SCORE.get(h_ceil, 2.0)
    score = b_floor * (1.0 - weight) + b_ceil * weight
    return round(score, 1)


def get_yandex_traffic_multiplier(
    t_min: int,
    from_coords: Tuple[float, float],
    to_coords: Tuple[float, float],
    transport: str
) -> float:
    """
    Рассчитывает динамический коэффициент задержки k_traffic(t, r_ij) по данным исследования Яндекса.

    - foot, bicycle, transit: возвращает 1.0 (полный иммунитет к дорожным пробкам).
    - car: возвращает коэффициент в диапазоне 1.0 ... 1.75 в зависимости от времени суток и направления.
    """
    # 1. Мультимодальный иммунитет
    if transport in ('foot', 'bicycle', 'transit'):
        return 1.0

    score = get_yandex_score(t_min)

    # 2. Базовый коэффициент задержки по баллу:
    # 1-2 балла: 1.00 - 1.05
    # 4 балла:   1.15
    # 7 баллов:  1.45
    # 8.2 балла: 1.65
    base_mult = 1.0 + max(0.0, (score - 1.5)) * 0.095

    # 3. Радиальная маятниковая асимметрия Яндекса:
    # В исследовании показано: утром Шоссе Энтузиастов и Волгоградка стоят В ЦЕНТР,
    # а вечером - ИЗ ЦЕНТРА в сторону области/МКАД.
    c_lat, c_lon = MOSCOW_CENTER_COORDS
    d_from_center_sq = (from_coords[0] - c_lat) ** 2 + (from_coords[1] - c_lon) ** 2
    d_to_center_sq = (to_coords[0] - c_lat) ** 2 + (to_coords[1] - c_lon) ** 2

    is_moving_to_center = d_to_center_sq < d_from_center_sq
    is_moving_from_center = d_to_center_sq > d_from_center_sq

    # Утренний час пик (07:30 - 10:15) - затор радиалов в сторону центра
    if 450 <= t_min <= 615 and is_moving_to_center:
        base_mult *= 1.15
    # Вечерний час пик (17:30 - 20:15) - затор радиалов из центра в область
    elif 1050 <= t_min <= 1215 and is_moving_from_center:
        base_mult *= 1.20

    # Ограничение сверху разумным порогом для планирования расписания
    return round(min(1.85, max(1.0, base_mult)), 2)


def get_traffic_badge_info(t_min: int) -> Dict[str, Any]:
    """
    Формирует метаданные для UI: текущий балл пробок, описание периода и рекомендации.
    """
    score = get_yandex_score(t_min)
    if score >= 7.5:
        level = "high"
        color = "#E53935"  # красный
        label = "Вечерний час пик (Яндекс 8+)"
        rec = "Авто задерживается до +75%. Рекомендуются пешие инженеры и метро."
    elif score >= 6.0:
        level = "med-high"
        color = "#FB8C00"  # оранжевый
        label = "Утренний час пик (Яндекс 7 баллов)"
        rec = "Заторы на радиалах в центр. Буфер окон: 15 мин."
    elif score >= 4.0:
        level = "med"
        color = "#FDD835"  # жёлтый
        label = "Дневной межпик (Яндекс 4 балла)"
        rec = "Умеренный трафик, движение стабильное."
    else:
        level = "low"
        color = "#43A047"  # зелёный
        label = "Свободные дороги (Яндекс 2-3 балла)"
        rec = "Свободное движение без задержек."

    return {
        "score": score,
        "level": level,
        "color": color,
        "label": label,
        "recommendation": rec
    }
